// Run only when updating the pinned editor packages; Docker and normal development need no Node build.
import { build } from 'esbuild';
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { resolve, dirname, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../', import.meta.url));
const output = resolve(root, 'app/static/vendor/code-editor.js');
const result = await build({
  absWorkingDir: root, entryPoints: ['scripts/code-editor-entry.mjs'], bundle: true,
  format: 'esm', platform: 'browser', target: 'es2022', minify: true,
  legalComments: 'none', write: false, metafile: true,
  banner: { js: '// @ts-nocheck\n// CodeMirror 6, MIT. Generated by npm run vendor:editor; see code-editor.LICENSE.txt.' },
});
const packages = new Map();
for (const input of Object.keys(result.metafile.inputs)) {
  if (!input.startsWith('node_modules/')) continue;
  let folder = dirname(resolve(root, input));
  while (!existsSync(resolve(folder, 'package.json'))) folder = dirname(folder);
  const pkg = JSON.parse(readFileSync(resolve(folder, 'package.json'), 'utf8'));
  const license = ['LICENSE', 'LICENSE.txt', 'LICENSE.md'].find((name) => existsSync(resolve(folder, name)));
  if (!license) throw new Error('Missing license: ' + pkg.name);
  packages.set(pkg.name, `${pkg.name}@${pkg.version}\n${readFileSync(resolve(folder, license), 'utf8').trim()}\n`);
}
const artifacts = new Map([
  [output, result.outputFiles[0].text],
  [output.replace('.js', '.d.ts'), readFileSync(resolve(root, 'scripts/code-editor-entry.mjs'), 'utf8')],
  [output.replace('.js', '.LICENSE.txt'), [...packages].sort(([a], [b]) => a.localeCompare(b)).map(([, text]) => text).join('\n-----\n\n')],
]);
for (const [file, content] of artifacts) {
  if (process.argv.includes('--check')) {
    if (readFileSync(file, 'utf8').replaceAll('\r\n', '\n') !== content.replaceAll('\r\n', '\n')) throw new Error('Rebuild ' + relative(root, file));
  } else writeFileSync(file, content);
}
console.log(`CodeMirror: ${packages.size} packages, ${Math.round(result.outputFiles[0].contents.length / 1024)} KiB, local ESM.`);
